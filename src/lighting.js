// ფერის ტემპერატურა → წრფივი RGB, სიკაშკაშე (Y) = 1 — K-ის ცვლილებისას ნაკადი არ იცვლება.
// პლანკის ლოკუსი: Kim et al. (2002) კუბური მიახლოება; XYZ → sRGB (D65).
export function cctRGB(T) {
  const T2 = T * T, T3 = T2 * T;
  const x = T <= 4000 ? -0.2661239e9 / T3 - 0.2343589e6 / T2 + 0.8776956e3 / T + 0.179910 : -3.0258469e9 / T3 + 2.1070379e6 / T2 + 0.2226347e3 / T + 0.240390;
  const x2 = x * x, x3 = x2 * x;
  const y = T <= 2222 ? -1.1063814 * x3 - 1.34811020 * x2 + 2.18555832 * x - 0.20219683
    : T <= 4000 ? -0.9549476 * x3 - 1.37418593 * x2 + 2.09137015 * x - 0.16748867
      : 3.0817580 * x3 - 5.87338670 * x2 + 3.75112997 * x - 0.37001483;
  const X = x / y, Z = (1 - x - y) / y;
  const r = Math.max(0, 3.2406 * X - 1.5372 - 0.4986 * Z), g = Math.max(0, -0.9689 * X + 1.8758 + 0.0415 * Z), b = Math.max(0, 0.0557 * X - 0.2040 + 1.0570 * Z);
  const lum = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  return [r / lum, g / lum, b / lum];
}

// ეკრანის „თეთრის ბალანსი“ (ფოტოკამერის მსგავსად): ფერები ნორმალიზდება 5000K-ზე — სხვაობა 3000K/4500K-ს შორის ჩანს,
// მაგრამ 3000K არ ხდება ზედმეტად ნარინჯისფერი (D65-ზე ბალანსისას ასე ხდება), 4500K — არ ხდება ლურჯი. ვარაუდი, რეგულირებადი.
export const WHITE_BALANCE = 5000;
export function lightRGB(T) {
  const c = cctRGB(T), w = cctRGB(WHITE_BALANCE);
  const v = c.map((x, i) => x / w[i]);
  const lum = 0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2];
  return v.map((x) => x / lum);
}
