function chain(xs, at, axis, status) {
  const out = [];
  for (let i = 1; i < xs.length; i++) {
    const a = axis === 'x' ? [xs[i - 1], at] : [at, xs[i - 1]];
    const b = axis === 'x' ? [xs[i], at] : [at, xs[i]];
    out.push({ a, b, text: (xs[i] - xs[i - 1]).toLocaleString('en-US').replace(',', ' '), status });
  }
  return out;
}
